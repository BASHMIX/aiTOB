"""The only runtime database transport for aiTOB.

SQLite remains available solely when an explicit ``DB_PATH`` is supplied by
tests or the migration tools.  A process configured with ``DATABASE_URL`` uses
PostgreSQL for every API, bot and worker query; it never falls back mid-run.
The compatibility surface intentionally mirrors the small async aiosqlite API
used by the pre-migration repositories while PostgreSQL conversion is rolled
out in focused batches.
"""
from __future__ import annotations

import os
import re
import asyncio
from collections.abc import Iterable
from types import SimpleNamespace
from typing import Any

import aiosqlite as _sqlite

# psycopg async cannot run on Windows' Proactor loop. Configure this before the
# API/bot creates its event loop; Linux deployments keep their normal policy.
if os.name == "nt" and hasattr(asyncio, "WindowsSelectorEventLoopPolicy"):
    asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())


def is_postgres() -> bool:
    return os.getenv("DATABASE_URL", "").strip().lower().startswith(("postgres://", "postgresql://"))


def _sqlite_is_explicitly_allowed() -> bool:
    return os.getenv("AITOB_TESTING") == "1" or os.getenv("AITOB_SQLITE_MIGRATION_TOOL") == "1"


RUNTIME_DATABASE_ERROR = (
    "DATABASE_URL is required for API, bot, and worker runtime; SQLite is limited "
    "to tests and explicit migration tools."
)


def require_runtime_database() -> str:
    """Fail before a service begins accepting work without PostgreSQL."""
    dsn = os.getenv("DATABASE_URL", "").strip()
    if dsn and not is_postgres():
        raise RuntimeError("DATABASE_URL must select PostgreSQL; no fallback is allowed")
    if not is_postgres() and not _sqlite_is_explicitly_allowed():
        raise RuntimeError(RUNTIME_DATABASE_ERROR)
    return dsn


def postgres_ddl(statement: str) -> str:
    value = statement.strip()
    value = re.sub(r"\bCOLLATE\s+NOCASE\b", "", value, flags=re.I)
    value = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", value, flags=re.I)
    value = re.sub(r"\bAUTOINCREMENT\b", "", value, flags=re.I)
    value = re.sub(r"(\bBOOLEAN\s+DEFAULT\s+)1\b", r"\1TRUE", value, flags=re.I)
    value = re.sub(r"(\bBOOLEAN\s+DEFAULT\s+)0\b", r"\1FALSE", value, flags=re.I)
    value = re.sub(r"ALTER TABLE (\w+) ADD COLUMN ", r"ALTER TABLE \1 ADD COLUMN IF NOT EXISTS ", value, flags=re.I)
    return value


def _bind_parameters(statement: str) -> str:
    """Translate bind markers only in executable SQL, never literals/comments."""
    out: list[str] = []
    i, state, dollar_tag = 0, "code", ""
    block_depth, escape_string = 0, False
    while i < len(statement):
        char = statement[i]
        next_char = statement[i + 1] if i + 1 < len(statement) else ""
        if state == "code":
            if char == "'":
                state = "single"
                escape_string = i > 0 and statement[i - 1] in "Ee" and (i < 2 or not (statement[i - 2].isalnum() or statement[i - 2] == "_"))
            elif char == '"': state = "double"
            elif char == "-" and next_char == "-": state = "line"
            elif char == "/" and next_char == "*":
                state, block_depth = "block", 1
                out.extend((char, next_char)); i += 2; continue
            elif char == "$":
                # PostgreSQL dollar-quoted bodies can contain bind-looking
                # text, quotes, and comments; none of it is executable SQL.
                match = re.match(r"\$[A-Za-z_][A-Za-z0-9_]*\$|\$\$", statement[i:])
                if match:
                    dollar_tag = match.group(0)
                    out.append(dollar_tag)
                    i += len(dollar_tag)
                    state = "dollar"
                    continue
            elif char == "?": out.append("%s"); i += 1; continue
            elif char == ":":
                if next_char == ":":
                    out.extend((char, next_char)); i += 2; continue
                match = re.match(r":([A-Za-z_][A-Za-z0-9_]*)", statement[i:])
                if match:
                    out.append(f"%({match.group(1)})s"); i += len(match.group(0)); continue
        elif state == "single" and escape_string and char == "\\":
            out.extend((char, next_char)); i += 2; continue
        elif state == "single" and char == "'":
            if next_char == "'": out.extend((char, next_char)); i += 2; continue
            state = "code"
        elif state == "double" and char == '"': state = "code"
        elif state == "line" and char == "\n": state = "code"
        elif state == "block" and char == "/" and next_char == "*":
            block_depth += 1
            out.extend((char, next_char)); i += 2; continue
        elif state == "block" and char == "*" and next_char == "/":
            block_depth -= 1
            out.extend((char, next_char)); i += 2
            if block_depth == 0: state = "code"
            continue
        elif state == "dollar" and statement.startswith(dollar_tag, i):
            out.append(dollar_tag)
            i += len(dollar_tag)
            dollar_tag = ""
            state = "code"
            continue
        out.append(char); i += 1
    return "".join(out)


def _query(statement: str, *, escape_percent: bool = False) -> str:
    value = statement.strip()
    if value.upper() == "BEGIN IMMEDIATE":
        return "BEGIN"
    if value.upper().startswith("PRAGMA FOREIGN_KEYS"):
        return "SELECT 1"
    table_info = re.fullmatch(r"PRAGMA\s+table_info\(([^)]+)\)", value, flags=re.I)
    if table_info:
        table = table_info.group(1).strip("`\"[] ")
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", table):
            raise ValueError("Invalid metadata table")
        return f"SELECT ordinal_position - 1 AS cid, column_name AS name, data_type AS type, is_nullable='NO' AS notnull, column_default AS dflt_value, FALSE AS pk FROM information_schema.columns WHERE table_schema='public' AND table_name='{table}' ORDER BY ordinal_position"
    value = re.sub(
        r"^INSERT\s+OR\s+REPLACE\s+INTO\s+(connections|global_settings)\s*\(\s*key\s*,\s*value\s*\)\s*VALUES\s*\(\s*\?\s*,\s*\?\s*\)\s*;?$",
        r"INSERT INTO \1 (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value",
        value,
        flags=re.I,
    )
    # The remaining legacy "OR IGNORE" call sites target tables with durable
    # unique keys. PostgreSQL's equivalent does not replace an existing row.
    ignored_insert = bool(re.match(r"INSERT\s+OR\s+IGNORE\s+INTO\b", value, flags=re.I))
    value = re.sub(r"^INSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", value, flags=re.I)
    if ignored_insert and not re.search(r"\bON\s+CONFLICT\b", value, flags=re.I):
        value = value.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    # aiTOB uses qmark and named SQLite parameters; values are always bound.
    return _bind_parameters(value.replace("%", "%%") if escape_percent else value)


class Row(dict):
    """dict-style PostgreSQL row that preserves the aiosqlite numeric access."""
    def __init__(self, columns: list[str], values: tuple[Any, ...]):
        super().__init__(zip(columns, values))
        self._values = values

    def __getitem__(self, key: Any) -> Any:
        return self._values[key] if isinstance(key, int) else super().__getitem__(key)


class _Cursor:
    def __init__(self, raw: Any):
        self._raw = raw

    def _row(self, value: tuple[Any, ...] | None) -> Row | None:
        if value is None:
            return None
        columns = [item.name for item in self._raw.description or ()]
        return Row(columns, value)

    async def fetchone(self):
        return self._row(await self._raw.fetchone())

    async def fetchall(self):
        return [self._row(value) for value in await self._raw.fetchall()]

    @property
    def description(self):
        # A few legacy bot tools construct dictionaries from DB-API metadata.
        return tuple((item.name,) for item in self._raw.description or ())

    @property
    def rowcount(self):
        return self._raw.rowcount

    async def __aenter__(self):
        return self

    async def __aexit__(self, exc_type, exc, tb):
        await self._raw.close()


class _Execute:
    def __init__(self, connection: "_Connection", statement: str, params: Iterable[Any] | None):
        self.connection = connection
        self.statement = statement
        self.params = params if isinstance(params, dict) else tuple(params or ())
        self.cursor = None

    async def _run(self) -> _Cursor:
        if self.cursor is None:
            raw = self.connection._raw.cursor()
            try:
                # PostgreSQL has no BEGIN IMMEDIATE mode. Start a normal
                # transaction and let each repository acquire its own
                # workspace/row-scoped lock before mutating data. A generic
                # advisory lock here would serialize unrelated Workspaces.
                await raw.execute(_query(self.statement, escape_percent=bool(self.params)), self.params or None)
            except BaseException:
                await raw.close()
                raise
            self.cursor = _Cursor(raw)
        return self.cursor

    def __await__(self):
        return self._run().__await__()

    async def __aenter__(self):
        return await self._run()

    async def __aexit__(self, exc_type, exc, tb):
        if self.cursor:
            await self.cursor.__aexit__(exc_type, exc, tb)


class _Connection:
    def __init__(self, dsn: str):
        self.dsn, self._raw, self.row_factory = dsn, None, None

    async def __aenter__(self):
        from psycopg import AsyncConnection, Error
        try:
            self._raw = await AsyncConnection.connect(self.dsn, connect_timeout=10)
        except (Error, ValueError):
            raise RuntimeError("PostgreSQL connection unavailable; service startup/work must stop") from None
        return self

    async def __aexit__(self, exc_type, exc, tb):
        if self._raw:
            try:
                if exc_type:
                    await self._raw.rollback()
            finally:
                await self._raw.close()

    def execute(self, statement: str, params: Iterable[Any] | None = None) -> _Execute:
        return _Execute(self, statement, params)

    async def executemany(self, statement: str, params_seq: Iterable[Iterable[Any]]):
        raw = self._raw.cursor()
        try:
            await raw.executemany(_query(statement, escape_percent=True), params_seq)
        finally:
            await raw.close()

    async def commit(self):
        await self._raw.commit()

    async def rollback(self):
        await self._raw.rollback()


class _SQLiteTestConnection:
    """Drain test/tool SQLite connector threads before cancellation propagates."""

    def __init__(self, path: str):
        self.raw = _sqlite.connect(path)

    async def __aenter__(self):
        opening = asyncio.ensure_future(self.raw)
        try:
            return await asyncio.shield(opening)
        except asyncio.CancelledError:
            try:
                await opening
            finally:
                await self.raw.close()
            raise

    async def __aexit__(self, exc_type, exc, tb):
        closing = asyncio.create_task(self.raw.close())
        try:
            await asyncio.shield(closing)
        except asyncio.CancelledError:
            await closing
            raise


def connect(path: str | None = None):
    require_runtime_database()
    dsn = os.getenv("DATABASE_URL", "").strip()
    if is_postgres():
        return _Connection(dsn)
    if not _sqlite_is_explicitly_allowed():
        raise RuntimeError(RUNTIME_DATABASE_ERROR)
    target = path or os.getenv("DB_PATH")
    if not target:
        raise RuntimeError("Explicit SQLite test/migration database path is required")
    return _SQLiteTestConnection(target)


# SQLite callers still need its native row_factory signature. PostgreSQL
# connections ignore ``row_factory`` and always return the compatible Row above.
dbapi = SimpleNamespace(connect=connect, Row=_sqlite.Row)
