"""One-way, auditable SQLite -> PostgreSQL migration for aiTOB.

This command deliberately has no dual-write mode and never opens the source
SQLite file for writing.  It is safe to use against a copied production file
first, then against an offline operational file during the final cutover.
Secrets remain ciphertext values; the command neither decrypts nor prints them.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import re
import sqlite3
import sys
from pathlib import Path
from typing import Iterable

import psycopg
from dotenv import load_dotenv
from psycopg import sql


ROOT = Path(__file__).resolve().parents[1]
SYSTEM_TABLES = {"sqlite_sequence"}
COPY_ORDER = (
    "users", "workspaces", "workspace_memberships", "user_sessions",
    "players", "overlays", "tournaments", "stations", "station_overlays",
    "active_matches", "tournament_player_links", "provider_bracket_snapshots",
    "integration_accounts", "integration_credentials", "integration_oauth_applications",
    "integration_destinations",
)


def postgres_ddl(statement: str) -> str:
    """Translate the constrained SQLite DDL used by database_schema.py."""
    value = statement.strip()
    value = re.sub(r"\bCOLLATE\s+NOCASE\b", "", value, flags=re.I)
    value = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        value,
        flags=re.I,
    )
    value = re.sub(r"\bAUTOINCREMENT\b", "", value, flags=re.I)
    # SQLite accepts integer literals for BOOLEAN defaults; PostgreSQL does not.
    value = re.sub(r"(\bBOOLEAN\s+DEFAULT\s+)1\b", r"\1TRUE", value, flags=re.I)
    value = re.sub(r"(\bBOOLEAN\s+DEFAULT\s+)0\b", r"\1FALSE", value, flags=re.I)
    value = re.sub(r"ALTER TABLE (\w+) ADD COLUMN ", r"ALTER TABLE \1 ADD COLUMN IF NOT EXISTS ", value, flags=re.I)
    return value


def source_tables(source: sqlite3.Connection) -> list[str]:
    tables = [
        str(row[0])
        for row in source.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name")
        if row[0] not in SYSTEM_TABLES
    ]
    priority = {name: index for index, name in enumerate(COPY_ORDER)}
    return sorted(tables, key=lambda name: (priority.get(name, len(COPY_ORDER)), name))


def source_columns(source: sqlite3.Connection, table: str) -> list[str]:
    quoted = '"' + table.replace('"', '""') + '"'
    return [str(row[1]) for row in source.execute(f"PRAGMA table_info({quoted})")]


def target_columns(conn: psycopg.Connection, table: str) -> list[str]:
    with conn.cursor() as cur:
        cur.execute(
            """SELECT column_name FROM information_schema.columns
               WHERE table_schema='public' AND table_name=%s ORDER BY ordinal_position""",
            (table,),
        )
        return [str(row[0]) for row in cur.fetchall()]


def target_boolean_columns(conn: psycopg.Connection, table: str) -> set[str]:
    with conn.cursor() as cur:
        cur.execute(
            """SELECT column_name FROM information_schema.columns
               WHERE table_schema='public' AND table_name=%s AND data_type='boolean'""",
            (table,),
        )
        return {str(row[0]) for row in cur.fetchall()}


def create_schema(conn: psycopg.Connection) -> None:
    from backend.core.database_schema import INDEXES, MIGRATIONS, TABLE_SCHEMAS

    with conn.cursor() as cur:
        for statement in TABLE_SCHEMAS:
            cur.execute(postgres_ddl(statement))
        for statement in MIGRATIONS:
            try:
                cur.execute(postgres_ddl(statement))
            except psycopg.errors.UndefinedTable:
                # Only an older optional table may be absent; all standard tables
                # are created above.  This mirrors the SQLite migration's safe
                # additive behavior without hiding malformed DDL.
                conn.rollback()
                raise
        for statement in INDEXES:
            cur.execute(postgres_ddl(statement))


def copy_table(source: sqlite3.Connection, target: psycopg.Connection, table: str) -> tuple[int, int]:
    source_cols = source_columns(source, table)
    target_cols = target_columns(target, table)
    missing = set(source_cols) - set(target_cols)
    if missing:
        raise RuntimeError(f"Unmapped source columns in {table}; explicit preservation migration required")
    common = [column for column in source_cols if column in target_cols]
    if not common:
        return 0, 0
    quoted_columns = sql.SQL(", ").join(sql.Identifier(column) for column in common)
    placeholders = sql.SQL(", ").join(sql.Placeholder() for _ in common)
    query = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(sql.Identifier(table), quoted_columns, placeholders)
    select = "SELECT " + ", ".join('"' + col.replace('"', '""') + '"' for col in common) + " FROM \"" + table.replace('"', '""') + "\""
    bool_indexes = {index for index, column in enumerate(common) if column in target_boolean_columns(target, table)}
    rows = [
        tuple(bool(value) if index in bool_indexes and value is not None else value for index, value in enumerate(row))
        for row in source.execute(select).fetchall()
    ]
    if rows:
        with target.cursor() as cur:
            try:
                cur.executemany(query, rows)
            except Exception as exc:
                # Identifiers and values can include player/provider data, so the
                # diagnostic names only the table and schema columns.
                raise RuntimeError(f"Cannot copy table {table}; transaction must roll back") from None
    with target.cursor() as cur:
        cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table)))
        copied = int(cur.fetchone()[0])
    return len(rows), copied


def validate(source: sqlite3.Connection, target: psycopg.Connection, tables: Iterable[str]) -> dict[str, int]:
    """Validate logical contents, not just counts, without exposing values.

    Values such as encrypted credentials remain opaque: their normalized digest
    is compared, never printed.  ISO timestamps are normalized to UTC because
    SQLite stores them as text while psycopg exposes ``datetime`` values.
    """
    mismatches: dict[str, int] = {}
    for table in tables:
        source_count = int(source.execute(f"SELECT COUNT(*) FROM \"{table}\"").fetchone()[0])
        with target.cursor() as cur:
            cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table)))
            target_count = int(cur.fetchone()[0])
        if source_count != target_count:
            mismatches[table] = target_count - source_count
            continue
        source_cols = source_columns(source, table)
        target_cols = target_columns(target, table)
        common = [column for column in source_cols if column in target_cols]
        if not common:
            continue
        source_rows = source.execute(
            "SELECT " + ", ".join('"' + c.replace('"', '""') + '"' for c in common) +
            " FROM \"" + table.replace('"', '""') + "\""
        ).fetchall()
        with target.cursor() as cur:
            cur.execute(sql.SQL("SELECT {} FROM {}").format(
                sql.SQL(", ").join(sql.Identifier(column) for column in common),
                sql.Identifier(table),
            ))
            target_rows = cur.fetchall()
        bool_indexes = {
            index for index, column in enumerate(common)
            if column in target_boolean_columns(target, table)
        }
        normalized_source_rows = [
            tuple(bool(value) if index in bool_indexes and value is not None else value for index, value in enumerate(row))
            for row in source_rows
        ]
        if _logical_digest(normalized_source_rows) != _logical_digest(target_rows):
            # A table-level count is enough for a redacted operational report;
            # the source values may contain tokens, URLs, or personal details.
            mismatches[table] = -1
        for index, column in enumerate(common):
            source_nulls = sum(row[index] is None for row in source_rows)
            target_nulls = sum(row[index] is None for row in target_rows)
            if source_nulls != target_nulls:
                mismatches[table] = -1
    return mismatches


def _normalize(value: object) -> object:
    if isinstance(value, dt.datetime):
        if value.tzinfo is None:
            value = value.replace(tzinfo=dt.timezone.utc)
        return ("timestamp", value.astimezone(dt.timezone.utc).isoformat(timespec="microseconds"))
    if isinstance(value, dt.date):
        return ("date", value.isoformat())
    if isinstance(value, memoryview):
        value = bytes(value)
    if isinstance(value, bytes):
        return ("bytes", hashlib.sha256(value).hexdigest())
    if isinstance(value, bool):
        return ("bool", value)
    if isinstance(value, float):
        return ("float", format(value, ".17g"))
    if value is None:
        return ("null", None)
    text = str(value)
    # PostgreSQL returns timestamps as objects; retain a logical equivalent
    # for SQLite text only when it is an unambiguous ISO timestamp.
    try:
        parsed = dt.datetime.fromisoformat(text.replace("Z", "+00:00"))
        if "T" in text or " " in text:
            if parsed.tzinfo is None:
                parsed = parsed.replace(tzinfo=dt.timezone.utc)
            return ("timestamp", parsed.astimezone(dt.timezone.utc).isoformat(timespec="microseconds"))
    except ValueError:
        pass
    return ("scalar", text)


def _logical_digest(rows: Iterable[tuple[object, ...]]) -> str:
    normalized = [json.dumps([_normalize(value) for value in row], sort_keys=True, separators=(",", ":")) for row in rows]
    return hashlib.sha256("\n".join(sorted(normalized)).encode("utf-8")).hexdigest()


def validate_relationships_and_sequences(source: sqlite3.Connection, target: psycopg.Connection, tables: Iterable[str]) -> list[str]:
    failures: list[str] = []
    if source.execute("PRAGMA foreign_key_check").fetchone() is not None:
        failures.append("source_foreign_keys")
    with target.cursor() as cur:
        # PostgreSQL validates imported foreign-key relationships at INSERT
        # time.  This explicit query catches constraints added after import.
        cur.execute("SELECT conname FROM pg_constraint WHERE contype='f' AND NOT convalidated")
        if cur.fetchall():
            failures.append("target_unvalidated_foreign_keys")
        for table in tables:
            columns = target_columns(target, table)
            if "id" not in columns:
                continue
            cur.execute("SELECT pg_get_serial_sequence(%s, 'id')", (table,))
            sequence = cur.fetchone()[0]
            if sequence:
                cur.execute(sql.SQL("SELECT setval({}, COALESCE((SELECT MAX(id) FROM {}), 1), true)").format(
                    sql.Literal(sequence), sql.Identifier(table)
                ))
    return failures


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=str(ROOT / "backend/core/database.sqlite"), help="SQLite source path; it is always opened mode=ro")
    parser.add_argument("--dsn", default=os.getenv("DATABASE_URL", ""), help="PostgreSQL DSN (prefer DATABASE_URL from ignored .env.production)")
    parser.add_argument(
        "--allow-schema-only-target",
        action="store_true",
        help="allow an existing PostgreSQL target only when every public table is empty",
    )
    args = parser.parse_args()
    load_dotenv(ROOT / ".env.production")
    dsn = args.dsn or os.getenv("DATABASE_URL", "")
    if not dsn.startswith("postgres"):
        raise SystemExit("DATABASE_URL must be an explicit PostgreSQL DSN.")
    source_path = Path(args.source).resolve()
    if not source_path.is_file():
        raise SystemExit("SQLite source file was not found.")

    source = sqlite3.connect(f"file:{source_path.as_posix()}?mode=ro", uri=True)
    tables = source_tables(source)
    if source.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
        raise SystemExit("SQLite source integrity check failed.")

    with psycopg.connect(dsn, autocommit=False) as target:
        with target.cursor() as cur:
            cur.execute("SELECT count(*) FROM information_schema.tables WHERE table_schema='public'")
            existing = int(cur.fetchone()[0])
        if existing:
            if not args.allow_schema_only_target:
                raise SystemExit("Target PostgreSQL database is not empty; refusing to merge data.")
            with target.cursor() as cur:
                cur.execute(
                    """SELECT table_name FROM information_schema.tables
                       WHERE table_schema='public' AND table_type='BASE TABLE'
                       ORDER BY table_name"""
                )
                target_tables = [str(row[0]) for row in cur.fetchall()]
                occupied = []
                for table in target_tables:
                    cur.execute(sql.SQL("SELECT COUNT(*) FROM {}").format(sql.Identifier(table)))
                    if int(cur.fetchone()[0]):
                        occupied.append(table)
            if occupied:
                raise SystemExit(
                    "Target PostgreSQL database has data; refusing to merge data: "
                    + ", ".join(occupied)
                )
        create_schema(target)
        copied = {}
        for table in tables:
            copied[table] = copy_table(source, target, table)
        mismatches = validate(source, target, tables)
        relationship_failures = validate_relationships_and_sequences(source, target, tables)
        if mismatches or relationship_failures:
            target.rollback()
            items = sorted(mismatches) + sorted(relationship_failures)
            raise SystemExit("Content/relationship validation failed; transaction rolled back: " + ", ".join(items))
        with target.cursor() as cur:
            cur.execute("""CREATE TABLE IF NOT EXISTS app_migrations (
                name TEXT PRIMARY KEY, source_fingerprint TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")
            logical_source = hashlib.sha256()
            for table in tables:
                columns = source_columns(source, table)
                quoted_table = '"' + table.replace('"', '""') + '"'
                logical_source.update(table.encode())
                logical_source.update(json.dumps(columns).encode())
                logical_source.update(_logical_digest(source.execute(f"SELECT * FROM {quoted_table}").fetchall()).encode())
            cur.execute("INSERT INTO app_migrations(name, source_fingerprint) VALUES (%s, %s)", ("sqlite-to-postgres-v1", logical_source.hexdigest()))
        target.commit()

    print(f"Migrated {len(tables)} tables and validated row counts. Source was opened read-only.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception:
        # Driver exceptions may include DSNs or failing row contents.
        print("Migration failed; transaction rolled back. Check schema/preservation tests before retrying.", file=sys.stderr)
        sys.exit(1)
